pub fn escape_string_for_thrust_literal(s: &str) -> String {
    let mut out: String = String::with_capacity(s.len().saturating_add(8));

    for ch in s.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            '\0' => out.push_str("\\0"),
            '\'' => out.push_str("\\'"),
            other => out.push(other),
        }
    }

    out
}
